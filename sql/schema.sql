-- echo-demo-app 순번 쓰기 장부. 앱이 시작할 때(AUTO_MIGRATE=true) 같은 파일을 실행한다.
-- 논리 복제는 DDL 을 옮기지 않으므로, 복제 대상 DB 에는 구독을 만들기 전에 이 파일을 먼저 적용한다:
--   psql "$TARGET_DATABASE_URL" -f sql/schema.sql
-- 여러 번 실행해도 안전하다(IF NOT EXISTS). id 는 논리 복제가 명시 값을 넣을 수 있게 BY DEFAULT 로 둔다.
CREATE SCHEMA IF NOT EXISTS demo;

CREATE TABLE IF NOT EXISTS demo.seq_write (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  n           bigint NOT NULL UNIQUE,
  wrote_at    timestamptz NOT NULL DEFAULT now(),
  written_env text NOT NULL DEFAULT 'unknown'
);

-- PoC 표(written_env 없음)에 칸만 더한다.
ALTER TABLE demo.seq_write ADD COLUMN IF NOT EXISTS written_env text NOT NULL DEFAULT 'unknown';
