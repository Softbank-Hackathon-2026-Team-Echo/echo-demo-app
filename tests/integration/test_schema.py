"""시작 때 스키마 맞춤(AUTO_MIGRATE)과 PoC 표 호환을 확인한다."""

import psycopg
import pytest

from tests.support import make_settings, running_client

pytestmark = pytest.mark.integration

# echo-infra PR #18 replication/sql/schema.sql 의 PoC 표(written_env 없음).
POC_TABLE_SQL = """
CREATE SCHEMA demo;
CREATE TABLE demo.seq_write (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  n        bigint NOT NULL UNIQUE,
  wrote_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO demo.seq_write (n) VALUES (1), (2);
"""


def _columns(conn: psycopg.Connection) -> list[str]:
    rows = conn.execute(
        "SELECT column_name FROM information_schema.columns"
        " WHERE table_schema = 'demo' AND table_name = 'seq_write' ORDER BY ordinal_position"
    ).fetchall()
    return [r[0] for r in rows]


async def test_startup_creates_schema_when_missing(
    database_url: str, admin_conn: psycopg.Connection
) -> None:
    admin_conn.execute("DROP SCHEMA IF EXISTS demo CASCADE")

    async with running_client(make_settings(database_url)) as client:
        assert _columns(admin_conn) == ["id", "n", "wrote_at", "written_env", "request_id"]
        response = await client.post("/api/writes")

    assert response.status_code == 201
    assert response.json()["n"] == 1


async def test_startup_adds_written_env_to_poc_table(
    database_url: str, admin_conn: psycopg.Connection
) -> None:
    admin_conn.execute("DROP SCHEMA IF EXISTS demo CASCADE")
    admin_conn.execute(POC_TABLE_SQL.encode())

    async with running_client(make_settings(database_url)) as client:
        body = (await client.post("/api/writes")).json()
        summary = (await client.get("/api/writes/summary")).json()

    assert _columns(admin_conn) == ["id", "n", "wrote_at", "written_env", "request_id"]
    assert body["n"] == 3
    assert summary["byEnvironment"] == [
        {"environment": "unknown", "count": 2, "minN": 1, "maxN": 2},
        {"environment": "aws-tokyo", "count": 1, "minN": 3, "maxN": 3},
    ]


async def test_auto_migrate_disabled_skips_schema_and_write_returns_503(
    database_url: str, admin_conn: psycopg.Connection
) -> None:
    admin_conn.execute("DROP SCHEMA IF EXISTS demo CASCADE")

    async with running_client(make_settings(database_url, auto_migrate=False)) as client:
        response = await client.post("/api/writes")

    assert response.status_code == 503
    assert response.json() == {"error": "DB_UNAVAILABLE"}
    assert _columns(admin_conn) == []
